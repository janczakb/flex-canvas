import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {chromium} from '@playwright/test'
import {serveViewerExample} from '../scripts/serve.mjs'
const example=await serveViewerExample(), browser=await chromium.launch()
try {
    const page=await browser.newPage({viewport:{width:1440,height:940}}),errors=[]
    page.setDefaultTimeout(8000)
    page.on('pageerror',error=>errors.push(error.message))
    await page.goto(example.url)
    await page.getByRole('button',{name:'Open image sample',exact:true}).click()
    await page.waitForFunction(()=>window.exampleViewer?.())
    const root=page.locator('.fm'),button=name=>root.getByRole('button',{name,exact:true})
    const stageBefore=await root.locator('.fm-stage').boundingBox()
    await button('Note').click()
    assert.deepEqual(await root.locator('.fm-stage').boundingBox(),stageBefore)
    const properties=root.getByRole('toolbar',{name:'Tool properties',exact:true})
    const colors=properties.getByRole('radiogroup',{name:'Note color',exact:true})
    const icons=properties.getByRole('radiogroup',{name:'Note icon',exact:true})
    await colors.waitFor()
    assert.equal(await colors.getByRole('radio').count(),6)
    assert.equal(await icons.getByRole('radio').count(),10)
    const layout=await icons.locator('.fm-note-choice').evaluateAll(nodes=>nodes.map(node=>({x:node.getBoundingClientRect().x,width:node.getBoundingClientRect().width,radius:getComputedStyle(node).borderRadius})))
    assert(layout.every(item=>parseFloat(item.radius)>=6))
    assert(layout.every((item,index)=>!index||item.x-layout[index-1].x-layout[index-1].width>=3.9))
    await icons.locator('label:has(input[value=star])').click()
    await colors.locator('label:has(input[value="#fff176"])').click()

    await page.waitForFunction(()=>Number(getComputedStyle(window.exampleViewer().element.shadowRoot.querySelector('.fm-context>.fm-bar')).opacity)===1)
    await mkdir('.internal/previews',{recursive:true})
    await page.screenshot({path:'.internal/previews/notes-toolbar-desktop.png'})
    const canvas=root.locator('.fm-stage>canvas').last(),box=await canvas.boundingBox()
    await page.mouse.click(box.x+box.width*.4,box.y+box.height*.4)
    const dialog=root.getByRole('dialog')
    await dialog.getByRole('textbox',{name:'Note',exact:true}).fill('Keep the entrance clear.')
    await dialog.getByRole('button',{name:'Done',exact:true}).click()
    let shapes=await page.evaluate(()=>window.exampleViewer().getState().annotations)
    assert.equal(shapes.length,1);assert.equal(shapes[0].text,'Keep the entrance clear.');assert.equal(shapes[0].noteIcon,'star');assert.equal(shapes[0].color,'#fff176')
    await icons.locator('label:has(input[value=pointer])').click()
    assert.equal((await page.evaluate(()=>window.exampleViewer().getState().annotations))[0].noteIcon,'pointer')
    const id=shapes[0].id
    await page.mouse.move(box.x+box.width*.4,box.y+box.height*.4);await page.mouse.down()
    await page.mouse.move(box.x+box.width*.55,box.y+box.height*.5,{steps:12});await page.mouse.up()
    shapes=await page.evaluate(()=>window.exampleViewer().getState().annotations)
    assert.equal(shapes.length,1);assert.equal(shapes[0].id,id)
    assert(Math.abs(shapes[0].points[0][0]-.55)<.01)
    assert.equal(shapes[0].text,'Keep the entrance clear.')
    await page.mouse.move(box.x+box.width*.55,box.y+box.height*.5)
    await root.locator('.fm-note-preview').getByText('Keep the entrance clear.',{exact:true}).waitFor()
    await page.mouse.click(box.x+box.width*.55,box.y+box.height*.5)
    await dialog.getByRole('textbox',{name:'Note',exact:true}).fill('Updated note')
    await dialog.getByRole('button',{name:'Done',exact:true}).click()
    await page.keyboard.press('Delete')
    await root.locator('.fm-confirm').getByRole('button',{name:'Cancel',exact:true}).click()
    assert.equal((await page.evaluate(()=>window.exampleViewer().getState().annotations)).length,1)
    await button('Notes and pins').click()
    const selectedMenu=root.getByRole('menuitemradio',{name:'Note',exact:true})
    const indicator=selectedMenu.locator('[data-slot=menu-item-indicator] svg')
    await selectedMenu.evaluate(async e=>{const p=e.closest('[data-slot=dropdown-popover]');await Promise.all(p.getAnimations({subtree:true}).map(animation=>animation.finished.catch(()=>{})))})
    assert.equal(await selectedMenu.getAttribute('aria-checked'),'true')
    assert(await indicator.isVisible())
    const rowBox=await selectedMenu.boundingBox(),checkBox=await indicator.boundingBox()
    assert(checkBox.width>=21.9&&checkBox.height>=21.9)
    assert(Math.abs(checkBox.y+checkBox.height/2-rowBox.y-rowBox.height/2)<.6)
    await page.screenshot({path:'.internal/previews/notes-dropdown.png'})
    await root.getByRole('menuitemradio',{name:'Numbered pin',exact:true}).click()
    assert.equal(await properties.getByRole('radiogroup',{name:'Note icon',exact:true}).count(),0)
    await page.mouse.click(box.x+box.width*.7,box.y+box.height*.65)
    await dialog.getByRole('textbox',{name:'Numbered pin',exact:true}).fill('Inspect this window.')
    await dialog.getByRole('button',{name:'Done',exact:true}).click()
    shapes=await page.evaluate(()=>window.exampleViewer().getState().annotations)
    assert.equal(shapes.length,2);assert.equal(shapes[1].tool,'pin');assert.equal(shapes[1].text,'Inspect this window.')
    const pinId=shapes[1].id
    await page.mouse.move(box.x+box.width*.7,box.y+box.height*.65);await page.mouse.down()
    await page.mouse.move(box.x+box.width*.75,box.y+box.height*.7,{steps:8});await page.mouse.up()
    shapes=await page.evaluate(()=>window.exampleViewer().getState().annotations)
    assert.equal(shapes.length,2);assert.equal(shapes[1].id,pinId)
    assert(Math.abs(shapes[1].points[0][0]-.75)<.01)
    await button('Save annotations').click()
    await page.getByText('Saved in this browser',{exact:true}).waitFor()
    assert.equal((await page.evaluate(()=>JSON.parse(localStorage.getItem('flex-viewer-example:image'))))[0].text,'Updated note')
    for(const width of [1024,768,390]){
        await page.setViewportSize({width,height:940})
        await page.waitForFunction(()=>window.exampleViewer().element.shadowRoot.querySelector('.fm-context>.fm-bar').dataset.compact==='true')
        await page.waitForFunction(width=>{const r=window.exampleViewer().element.shadowRoot.querySelector('.fm'),stage=r.querySelector('.fm-stage');return Math.abs(r.clientWidth-width)<1&&stage.clientWidth<=r.querySelector('.fm-scroll').clientWidth-23},width)
        const stageBefore=await root.locator('.fm-stage').boundingBox()
        await properties.getByRole('button',{name:'Pin color',exact:true}).click()
        assert(await properties.getByRole('button',{name:'Back to document tools',exact:true}).isVisible())
        assert.deepEqual(await root.locator('.fm-stage').boundingBox(),stageBefore)
        await properties.getByRole('button',{name:'Back to document tools',exact:true}).click()
        assert(await root.evaluate(e=>e.scrollWidth<=e.clientWidth+1))
    }
    await page.screenshot({path:'.internal/previews/notes-toolbar-mobile.png'})
    await page.evaluate(()=>window.exampleViewer().destroy())
    assert.deepEqual(errors,[])
    console.log(JSON.stringify({notes:true,inlineColors:6,inlineIcons:10,noteAndPin:true,responsiveWidths:[1024,768,390],markerDrag:true,hoverPreview:true,edit:true,deleteCancel:true,savedPayload:true,independent:true}))
} finally {await browser.close();await example.close()}
