import assert from 'node:assert/strict'
import {mkdir} from 'node:fs/promises'
import {chromium} from '@playwright/test'
import {serveViewerExample} from '../scripts/serve.mjs'
const example=await serveViewerExample(),browser=await chromium.launch()
try{
    const page=await browser.newPage({viewport:{width:1440,height:940}}),errors=[]
    page.setDefaultTimeout(8000);page.on('pageerror',error=>errors.push(error.message))
    await page.goto(example.url)
    await page.getByRole('button',{name:'Open image sample',exact:true}).click()
    await page.waitForFunction(()=>window.exampleViewer?.())
    const root=page.locator('.fm'),button=name=>root.getByRole('button',{name,exact:true})
    const hover=async locator=>{await locator.hover()}
    const tooltip=async label=>{
        const tip=root.getByRole('tooltip',{name:label,exact:true})
        await tip.waitFor()
        const style=await tip.evaluate(node=>({hero:node.classList.contains('tooltip'),owned:node.classList.contains('fm-tooltip'),background:getComputedStyle(node).backgroundColor,color:getComputedStyle(node).color}))
        assert.deepEqual(style,{hero:true,owned:true,background:'rgb(17, 17, 20)',color:'rgb(255, 255, 255)'})
        assert.equal(await root.locator('.fm-tip').count(),0)
        return tip
    }
    const menu=root.getByRole('menu',{name:'Drawing tools',exact:true})
    const menuTrigger=button('Drawing tools')
    const closed=async()=>{
        await menu.waitFor({state:'hidden'})
        assert.equal(await menuTrigger.getAttribute('aria-expanded'),'false')
    }
    await menuTrigger.click();await menu.waitFor()
    await button('Zoom in').click();await closed()
    await menuTrigger.click();await menu.waitFor()
    await menuTrigger.click();await closed()
    await menuTrigger.click();await menu.waitFor()
    await root.getByRole('menuitemradio',{name:'Freeform Highlight',exact:true}).click();await closed()
    await menuTrigger.click();await menu.waitFor()
    await page.keyboard.press('Escape');await closed()
    assert.equal(await menuTrigger.evaluate(node=>node.getRootNode().activeElement===node),true)
    await menuTrigger.click();await menu.waitFor()
    await button('Text tools').click()
    await closed()
    await root.getByRole('menu',{name:'Text tools',exact:true}).waitFor()
    await page.keyboard.press('Escape')
    await button('Select and move').click()
    await menuTrigger.click();await menu.waitFor()
    await root.locator('.fm-stage>canvas').last().click({position:{x:20,y:20}});await closed()
    assert.equal(await root.getByRole('dialog').count(),0)
    await hover(button('Print'));await tooltip('Print')
    await hover(button('Zoom in'));await tooltip('Zoom in')
    await root.focus();await page.keyboard.press('Tab')
    const keyboardTip=await tooltip('Select and move')
    const tooltipId=await keyboardTip.getAttribute('id')
    assert((await button('Select and move').getAttribute('aria-describedby'))?.split(/\s+/).includes(tooltipId))
    const split=root.locator('.fm-edit-tools>.fm-split').first()
    const main=split.locator('button').first(),arrow=split.locator('button').last()
    const before=await split.boundingBox()
    for(const target of [main,arrow]){
        await hover(target)
        const colors=await split.evaluate(node=>({group:getComputedStyle(node).backgroundColor,children:[...node.querySelectorAll('button')].map(button=>({background:getComputedStyle(button).backgroundColor,border:getComputedStyle(button).borderInlineEndWidth}))}))
        assert.equal(colors.group,'rgb(232, 233, 237)')
        assert(colors.children.every(child=>child.background==='rgba(0, 0, 0, 0)'&&child.border==='0px'))
        assert.deepEqual(await split.boundingBox(),before)
    }
    await tooltip('Drawing tools')
    await arrow.click()
    await root.getByRole('menu',{name:'Drawing tools',exact:true}).waitFor()
    await page.waitForFunction(()=>!window.exampleViewer().element.shadowRoot.querySelector('.fm-tooltip:not([data-exiting=true])'))
    await page.keyboard.press('Escape')
    await button('Note').click()
    const star=root.locator('.fm-note-icons label:has(input[value=star])')
    await hover(star);await tooltip('Star')
    await page.evaluate(()=>window.exampleViewer().setTheme('dark'))
    await hover(button('Zoom out'));await tooltip('Zoom out')
    await page.evaluate(()=>window.exampleViewer().setTheme('light'))
    await menuTrigger.click();await root.getByRole('menuitemradio',{name:'Drawing',exact:true}).click()
    await hover(root.locator('.fm-property[data-property=opacity] [data-slot=select-trigger]'))
    await tooltip('Opacity')
    const opacity=root.locator('.fm-property[data-property=opacity] [data-slot=select-trigger]')
    const options=root.locator('[data-slot=select-popover]').getByRole('listbox')
    await opacity.click();await options.waitFor()
    await button('Zoom in').click();await options.waitFor({state:'hidden'})
    await opacity.click();await options.waitFor()
    await opacity.click();await options.waitFor({state:'hidden'})
    await opacity.click();await options.getByRole('option',{name:'50%',exact:true}).click()
    await options.waitFor({state:'hidden'})
    assert.equal((await opacity.innerText()).trim(),'50%')
    await opacity.click();await options.waitFor()
    await page.keyboard.press('Escape');await options.waitFor({state:'hidden'})
    const color=root.locator('.fm-property[data-property=color] [data-slot=color-picker-trigger]')
    const palette=root.locator('[data-slot=color-picker-popover]')
    await color.click();await palette.waitFor()
    await button('Zoom in').click();await palette.waitFor({state:'hidden'})
    await color.click();await palette.waitFor()
    await color.click();await palette.waitFor({state:'hidden'})
    await color.click();await palette.waitFor()
    await palette.getByRole('option').nth(1).click();await palette.waitFor({state:'hidden'})
    await color.click();await palette.waitFor()
    await page.keyboard.press('Escape');await palette.waitFor({state:'hidden'})
    await page.setViewportSize({width:390,height:844})
    await page.waitForFunction(()=>window.exampleViewer().element.shadowRoot.querySelector('.fm-context>.fm-bar').dataset.compact==='true')
    const stroke=root.locator('[data-property-summary=stroke]')
    await hover(stroke);await tooltip('Stroke width')
    await menuTrigger.click();await menu.waitFor()
    await menuTrigger.click();await closed()
    await menuTrigger.click();await menu.waitFor()
    await button('Zoom in').click();await closed()
    await page.setViewportSize({width:1440,height:940})
    await menuTrigger.click();await menu.waitFor()
    await page.waitForFunction(()=>{const menu=window.exampleViewer().element.shadowRoot.querySelector('[data-slot=dropdown-popover]');return menu&&getComputedStyle(menu).opacity==='1'&&!menu.hasAttribute('data-entering')})
    await mkdir('.internal/previews',{recursive:true})
    await page.screenshot({path:'.internal/previews/toolbar-feedback.png',clip:{x:0,y:0,width:1440,height:380}})
    await page.evaluate(()=>window.exampleViewer().destroy())
    assert.equal(await root.count(),0)
    assert.deepEqual(errors,[])
    console.log(JSON.stringify({singleHeroUITooltip:true,blackInBothThemes:true,noteAndPropertyTooltips:true,dropdownDismissal:true,splitGroupHover:true,noInternalBorder:true,mobile:true,disposal:true}))
}catch(error){console.error(error);process.exitCode=1}
finally{await browser.close();await example.close()}
