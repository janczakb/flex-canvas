import assert from 'node:assert/strict'
import {chromium,firefox,webkit} from '@playwright/test'
import {serveViewerExample} from '../scripts/serve.mjs'
import {installBrochureFixture} from './fixtures/brochure.mjs'
const engine=process.env.BROWSER??'chromium',example=await serveViewerExample(),browser=await ({chromium,firefox,webkit}[engine]).launch()
try{
 const page=await browser.newPage({viewport:{width:1440,height:940}}),errors=[]
 page.setDefaultTimeout(12000);page.on('pageerror',error=>errors.push(error.message))
 await installBrochureFixture(page,{pages:12,landscape:false})
 await page.goto(example.url)
 await page.getByRole('button',{name:'Open Leela brochure',exact:true}).click()
 await page.waitForFunction(()=>window.exampleViewer?.())
 const root=page.locator('.fm'),number=root.getByRole('textbox',{name:'Page',exact:true})
 await root.getByRole('button',{name:'Page display',exact:true}).click()
 await root.getByRole('menuitemradio',{name:'Continuous scroll',exact:true}).click()
 await root.locator('[data-page-index="0"]:not([data-loading]) .fm-text').waitFor()
 const fit=await root.locator('[data-page-index="0"]').evaluate(el=>{const p=el.getBoundingClientRect(),v=el.closest('.fm-scroll').getBoundingClientRect();return{height:p.height,width:p.width,viewHeight:v.height,viewWidth:v.width,top:p.top-v.top,bottom:v.bottom-p.bottom}})
 assert(fit.height<=fit.viewHeight-40&&fit.width<=fit.viewWidth-40,'Portrait cover must fit the whole available viewport at default zoom')
 assert(fit.top>=20&&fit.bottom>=20)
 // Use the real pager while background neighbor rendering is still active.
 await number.fill('3');await number.press('Enter')
 await page.waitForFunction(()=>window.exampleViewer().getState().pageIndex===2)
 assert.equal(await number.inputValue(),'3')
 assert.equal(await number.evaluate(n=>n.getRootNode().activeElement===n),false,'Enter must release pager focus')
 const viewport=root.locator('.fm-scroll'),box=await viewport.boundingBox()
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2)
 await page.mouse.wheel(0,700)
 await page.waitForFunction(()=>window.exampleViewer().getState().pageIndex>2)
 assert.equal(await number.evaluate(n=>n.getRootNode().activeElement===n),false,'Wheel scrolling must never focus the pager')
 // Leaving a draft in the pager and then scrolling the document must not jump back to that draft.
 await number.fill('1')
 const before=await viewport.evaluate(n=>n.scrollTop)
 await page.mouse.move(box.x+box.width/2,box.y+box.height/2);await page.mouse.wheel(0,450)
 await page.waitForFunction(before=>window.exampleViewer().element.shadowRoot.querySelector('.fm-scroll').scrollTop>before,before)
 assert.equal(await number.evaluate(n=>n.getRootNode().activeElement===n),false)
 assert((await viewport.evaluate(n=>n.scrollTop))>before)
 await page.waitForFunction(()=>window.exampleViewer().element.shadowRoot.querySelector('.fm-pager input').value===String(window.exampleViewer().getState().pageIndex+1))
 // SDK zoom is an actual scale and both fitting modes remain public operations.
 await page.evaluate(()=>window.exampleViewer().setZoom(1.5))
 assert(Math.abs(await page.evaluate(()=>window.exampleViewer().getState().zoomLevel)-1.5)<.01)
 await page.evaluate(()=>window.exampleViewer().fitWidth())
 assert.equal(await page.evaluate(()=>window.exampleViewer().getState().zoomMode),'fit-width')
 await page.evaluate(()=>window.exampleViewer().fitPage())
 assert.equal(await page.evaluate(()=>window.exampleViewer().getState().zoomMode),'fit-page')
 // Fit is a single cycling control; its icon and tooltip describe the next operation.
 const fitToggle=root.locator('button[data-control=fit]')
 assert.equal(await fitToggle.getAttribute('aria-label'),'Fit width')
 const pageIcon=await fitToggle.locator('svg').innerHTML()
 await fitToggle.click()
 await page.waitForFunction(()=>window.exampleViewer().getState().zoomMode==='fit-width')
 assert.equal(await fitToggle.getAttribute('aria-label'),'Fit page')
 assert.notEqual(await fitToggle.locator('svg').innerHTML(),pageIcon)
 assert.equal(await root.getByRole('menu',{name:'Zoom',exact:true}).count(),0)
 await fitToggle.click()
 await page.waitForFunction(()=>window.exampleViewer().getState().zoomMode==='fit-page')
 const viewportSize={width:390,height:844};await page.setViewportSize(viewportSize)
 await page.evaluate(()=>window.exampleViewer().setPage(0))
 await page.waitForFunction(()=>window.exampleViewer().getState().pageIndex===0)
 const small=await root.locator('[data-page-index="0"]').evaluate(el=>{const p=el.getBoundingClientRect(),v=el.closest('.fm-scroll').getBoundingClientRect();return{h:p.height,w:p.width,vh:v.height,vw:v.width}})
 assert(small.h<=small.vh&&small.w<=small.vw)
 await page.evaluate(()=>window.exampleViewer().destroy())
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({engine,fitViewport:fit,mobile:small,pagerEnter:true,wheelDoesNotFocusPager:true,scrollDiscardsDraft:true,errors:0}))
}finally{await browser.close();await example.close()}
