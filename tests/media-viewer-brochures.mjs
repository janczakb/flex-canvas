import assert from 'node:assert/strict'
import {chromium,firefox,webkit} from '@playwright/test'
import {serveViewerExample} from '../scripts/serve.mjs'
const engine=process.env.BROWSER??'chromium',example=await serveViewerExample(),browser=await({chromium,firefox,webkit}[engine]).launch()
try{
    const page=await browser.newPage({viewport:{width:1440,height:940}}),errors=[],proofs=[]
    page.setDefaultTimeout(60000)
    page.on('pageerror',error=>errors.push(error.message))
    await page.goto(example.url)
    assert.equal(await page.locator('.fm').count(),0,'Viewer must not mount before a document is opened')
    for(const [id,title]of[['marly','Open Marly brochure'],['leela','Open Leela brochure']]){
        const start=performance.now()
        await page.getByRole('button',{name:title,exact:true}).click()
        await page.waitForFunction(()=>window.exampleViewer?.())
        const root=page.locator('.fm'),pages=await page.evaluate(()=>window.exampleViewer().getState().pageCount)
        assert(pages>4)
        await root.locator('.fm-pdf-tiles canvas[data-loaded="true"]').first().waitFor()
        const openedMs=Math.round(performance.now()-start)
        const box=await root.boundingBox();assert.equal(box.width,1440);assert.equal(box.height,940)
        await root.getByRole('button',{name:'Thumbnails',exact:true}).click()
        await root.locator('.fm-navigation-list canvas[data-loaded="true"]').first().waitFor()
        const thumbnailCount=await root.locator('.fm-navigation-list canvas').count()
        assert(thumbnailCount<=24)
        await page.evaluate(()=>window.exampleViewer().setPage(4))
        await page.waitForFunction(()=>window.exampleViewer().getState().pageIndex===4)
        await root.locator('.fm-pdf-tiles canvas[data-loaded="true"]').first().waitFor()
        await root.getByRole('button',{name:'Thumbnails',exact:true}).click()
        await page.screenshot({path:'.internal/'+id+'-modal.png'})
        const tileCount=await root.locator('.fm-pdf-tiles canvas').count()
        assert(tileCount<=64)
        if(id==='leela'){
            await page.evaluate(()=>window.exampleViewer().setPage(2))
            await page.waitForFunction(()=>window.exampleViewer().element.shadowRoot.querySelector('.fm-text')?.textContent.includes('STUNNING'))
            const heading=await root.locator('.fm-text').evaluate(layer=>{
                const lines=new Map()
                for(const span of layer.querySelectorAll('[data-fff-text-line]')){const key=span.dataset.fffTextLine;if(!lines.has(key))lines.set(key,[]);lines.get(key).push(span)}
                const values=[...lines.values()],first=values.find(row=>row.map(x=>x.textContent).join('').includes('STUNNING')),last=values.find(row=>row.map(x=>x.textContent).join('').includes('DESTINATIONS'))
                return {start:first[0].getBoundingClientRect().toJSON(),end:last.at(-1).getBoundingClientRect().toJSON()}
            })
            await page.mouse.move(heading.start.x+1,heading.start.y+heading.start.height/2);await page.mouse.down()
            await page.mouse.move(heading.end.x+heading.end.width-1,heading.end.y+heading.end.height/2,{steps:20});await page.mouse.up()
            await root.getByRole('toolbar',{name:'Selected text actions',exact:true}).waitFor()
            assert.equal(await root.locator('.fm-text-selection>span').count(),2,'Hotel heading must have two continuous selected lines')
            await page.screenshot({path:'.internal/previews/leela-text-selection.png'})
            await page.evaluate(()=>window.exampleViewer().setScrollMode('continuous'))
            await page.evaluate(()=>window.exampleViewer().setPage(20))
            await page.waitForFunction(()=>window.exampleViewer().getState().pageIndex===20)
            assert(await root.locator('.fm-flow-page').count()<=8)
            assert(await root.locator('.fm-text [data-fff-text-box]').count()>0)
        }
        if(id==='marly'){
            await page.evaluate(()=>window.exampleViewer().setPage(2))
            await page.waitForFunction(()=>window.exampleViewer().getState().pageIndex===2)
            await root.getByRole('button',{name:'Document editing tools',exact:true}).click()
            await root.getByRole('menuitemradio',{name:'Content editor',exact:true}).click()
            await root.locator('.fm-content-preparation').waitFor({state:'hidden'})
            const blocks=root.locator('.fm-content-block')
            await blocks.first().waitFor()
            assert.equal(await root.getByRole('button',{name:'Edit text fi',exact:true}).count(),0,'Ligatures cannot become separate editable layers')
            const paragraph=await page.evaluate(async()=>{
                const {openPDF}=await import('/dist/pdf.js'),{groupPDFParagraphs}=await import('/dist/pdf/text-paragraphs.js')
                const doc=await openPDF({source:'/brochures/marly.pdf',workerUrl:'/dist/pdfium-worker.js',wasmUrl:'/dist/pdfium.wasm'})
                try{return groupPDFParagraphs(await doc.getTextBlocks(2),(await doc.getPageInfo(2)).height).find(block=>block.text.startsWith('En plein cœur'))}finally{await doc.destroy()}
            })
            assert(paragraph.text.includes('confidentielle.'),'Native grouping preserves the full word including its fi fragment')
            const original=paragraph.lines.map(line=>line.text).join(' '),offset=original.indexOf('confidentielle')+5
            const character=paragraph.characters.find(character=>character.start===offset),stage=await root.locator('.fm-stage').boundingBox()
            assert(character)
            await page.mouse.click(stage.x+character.x*stage.width,stage.y+(character.y+character.height/2)*stage.height)
            const paragraphInput=root.getByRole('textbox',{name:'Edit text',exact:true}),caret=root.locator('.fm-content-caret:not([hidden])')
            assert.equal(await paragraphInput.inputValue(),original)
            assert.equal(await paragraphInput.evaluate(input=>input.selectionStart),offset,'Clicking a PDF glyph places the input at that same character')
            await caret.waitFor()
            const cursor=await caret.boundingBox()
            assert(Math.abs(cursor.x-stage.x-character.x*stage.width)<1,'The displayed caret uses the native font geometry')
            await paragraphInput.pressSequentially('c')
            assert.equal(await paragraphInput.inputValue(),original.slice(0,offset)+'c'+original.slice(offset))
            await root.locator('.fm-content-caret[data-offset="'+(offset+1)+'"]:not([hidden])').waitFor()
            await paragraphInput.press('ControlOrMeta+End')
            await root.locator('.fm-content-caret[data-offset="'+(original.length+1)+'"]:not([hidden])').waitFor()
            await paragraphInput.pressSequentially('e')
            assert.equal(await paragraphInput.inputValue(),original.slice(0,offset)+'c'+original.slice(offset)+'e','Typing at the visible end must append at the actual end')
            await root.locator('.fm-content-caret[data-offset="'+(original.length+2)+'"]:not([hidden])').waitFor()
            await page.screenshot({path:'.internal/previews/marly-native-caret.png'})
            await paragraphInput.fill(original)
            await paragraphInput.press('ControlOrMeta+a')
            assert.equal(await root.locator('.fm-content-text-selection>span').count(),2,'Selecting the paragraph uses its two actual PDF lines')
            const from=paragraph.characters.find(character=>character.start===3),to=paragraph.characters.find(character=>character.start===11)
            await page.mouse.move(stage.x+from.x*stage.width,stage.y+(from.y+from.height/2)*stage.height);await page.mouse.down()
            await page.mouse.move(stage.x+to.x*stage.width,stage.y+(to.y+to.height/2)*stage.height,{steps:10});await page.mouse.up()
            assert.deepEqual(await paragraphInput.evaluate(input=>[input.selectionStart,input.selectionEnd]),[3,11],'Mouse selection maps to the PDF characters')
            await paragraphInput.pressSequentially('e')
            assert.equal(await paragraphInput.inputValue(),original.slice(0,3)+'e'+original.slice(11))
            await paragraphInput.fill(original)
            const target=blocks.first(),initial=await target.boundingBox()
            await target.hover()
            assert.equal(await target.evaluate(node=>getComputedStyle(node).backgroundColor),'rgba(0, 0, 0, 0)')
            await target.click()
            const input=root.getByRole('textbox',{name:'Edit text',exact:true}),value=await input.inputValue()
            await input.fill(value+' ')
            await root.locator('.fm-content-raster canvas:not([hidden])').waitFor()
            assert((await root.locator('.fm-content-selection').boundingBox()).height>=initial.height-1,'Typing must not collapse a real scaled-font paragraph')
            await page.screenshot({path:'.internal/previews/marly-content-width.png'})
            await input.fill(value+' '+value+' '+value)
            await root.locator('.fm-content-raster canvas:not([hidden])').waitFor()
            await page.waitForFunction(()=>window.exampleViewer().element.shadowRoot.querySelector('.fm-content-selection')?.style.height!==undefined)
            const resized=await root.locator('.fm-content-selection').boundingBox()
            assert(Math.abs(initial.width-resized.width)<1,'Real brochure text must preserve its chosen width')
            await root.getByRole('button',{name:'Resize text area from right',exact:true}).waitFor()
            await root.locator('.fm-content-controls').getByRole('button',{name:'Cancel',exact:true}).click()
            await root.locator('.fm-confirm[open] button[data-control=discard]').click()
        }
        await root.getByRole('button',{name:'Close',exact:true}).click()
        await root.waitFor({state:'detached'})
        proofs.push({id,pages,openedMs,thumbnailCount,tileCount,fullscreen:true,closed:true})
    }
    assert.deepEqual(errors,[])
    console.log(JSON.stringify({engine,brochures:proofs,nativeCaret:true,ligatureGrouping:true,mouseTextSelection:true,errors,note:'Local cached brochures and local browser; not a cross-product performance comparison'}))
}finally{await browser.close();await example.close()}
